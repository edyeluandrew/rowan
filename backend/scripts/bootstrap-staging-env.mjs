/**
 * Bootstrap backend/.env.staging from backend/.env (same repo, phase-2/foundation).
 *
 * Copies all keys from .env, then overrides staging-only values.
 * Never prints secret values.
 *
 * Usage:
 *   node scripts/bootstrap-staging-env.mjs
 *   node scripts/bootstrap-staging-env.mjs --apply-local
 *
 * --apply-local  Also writes backend/.env from .env.staging (use when developing
 *                on phase-2/foundation against Neon locally).
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const backendDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(backendDir, '.env');
const stagingPath = path.join(backendDir, '.env.staging');
const localPath = path.join(backendDir, '.env');

const STAGING_OVERRIDES = {
  NODE_ENV: 'staging',
  PORT: '4000',

  // ── MUST CHANGE for staging (isolated from production) ──
  DATABASE_URL: 'postgresql://USER:PASSWORD@ep-xxxx.us-east-1.aws.neon.tech/neondb?sslmode=require',
  // Render Redis — share prod REDIS_URL for testnet staging (no separate instance required)
  // REDIS_URL: copied from production .env / Render dashboard

  // Staging Render service URL (update after first deploy)
  API_URL: 'https://rowan-backend-staging.onrender.com',

  // Staging frontends (Vercel preview or dedicated staging domains)
  CORS_ORIGIN:
    'http://localhost:5173,http://localhost:5174,https://rowan-staging.vercel.app,https://rowan-admin-staging.vercel.app',

  // Optional: separate JWT/encryption for staging (recommended — generate new 32+ char strings)
  // JWT_SECRET: 'CHANGE_ME_staging_jwt_min_32_chars________',
  // ENCRYPTION_KEY: 'CHANGE_ME_staging_encryption_32_chars__',

  // Rwanda rate (Phase 2 E1)
  USDC_RATE_RWF: '1300',
};

function parseEnv(raw) {
  const map = new Map();
  for (const line of raw.split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    const value = line.slice(eq + 1);
    map.set(key, value);
  }
  return map;
}

function serializeEnv(map, headerLines = []) {
  const lines = [...headerLines];
  for (const [key, value] of map.entries()) {
    lines.push(`${key}=${value}`);
  }
  return lines.join('\n') + '\n';
}

if (!fs.existsSync(sourcePath)) {
  console.error('Missing backend/.env — copy backend/.env.example first and fill production values.');
  process.exit(1);
}

const source = parseEnv(fs.readFileSync(sourcePath, 'utf8'));
for (const [key, value] of Object.entries(STAGING_OVERRIDES)) {
  source.set(key, value);
}

const header = [
  '# Rowan backend — STAGING (phase-2/foundation)',
  '# Generated by scripts/bootstrap-staging-env.mjs — do NOT commit',
  '#',
  '# Fill in: DATABASE_URL (Neon), REDIS_URL (staging Upstash), API_URL after Render deploy',
  '# Share Stellar/Supabase/JWT with prod for testnet OR rotate for isolation',
  '',
];

fs.writeFileSync(stagingPath, serializeEnv(source, header));
console.log('Wrote', stagingPath);
console.log('Override keys:', Object.keys(STAGING_OVERRIDES).join(', '));

const applyLocal = process.argv.includes('--apply-local');
if (applyLocal) {
  fs.writeFileSync(localPath, fs.readFileSync(stagingPath, 'utf8'));
  console.log('Applied staging env to backend/.env (--apply-local)');
}

console.log('\nNext: edit backend/.env.staging and set Neon DATABASE_URL + staging REDIS_URL');
